function generateChartData(basePrice: number, volatility: number = 0.015, points: number = 24) {
  const data = [];
  let current = basePrice * (1 - volatility * 2);
  const now = new Date();
  for (let i = points; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 3600 * 1000);
    const timeStr = `${time.getHours().toString().padStart(2, '0')}:00`;
    const randomShift = (Math.random() - 0.48) * volatility * basePrice;
    current = Math.max(0.1, current + randomShift);
    data.push({
      time: timeStr,
      price: parseFloat(current.toFixed(2)),
      volume: Math.floor(Math.random() * 50000 + 10000),
    });
  }
  // Ensure the last point is exact
  if (data.length > 0) {
    data[data.length - 1].price = basePrice;
  }
  return data;
}

